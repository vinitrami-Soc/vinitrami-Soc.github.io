/* Build the shareable demo of the dashboard.
 *
 * The published-artifact host wraps the page in its own document skeleton and
 * enforces its own CSP, so the shareable build is the same app with the outer
 * document removed and our meta policy dropped. Everything else — the assets,
 * the engine, the demo dataset — ships unchanged, so what a reviewer clicks is
 * the code in this repo, not a mock-up of it.
 *
 * Usage: node scripts/build-artifact.mjs  ->  dist/artifact/
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist", "artifact");
mkdirSync(join(out, "assets"), { recursive: true });

let html = readFileSync(join(root, "web", "index.html"), "utf8");

// 1. drop our meta CSP — the host enforces its own, and ours would fight it
html = html.replace(/<!-- A SOC tool renders[\s\S]*?object-src 'none'">\n/, "");
html = html.replace(/<!-- frame-ancestors is ignored[\s\S]*?headers\. -->\n/, "");

// 2. unwrap the document: the host supplies doctype/html/head/body
const head = html.slice(html.indexOf("<head>") + 6, html.indexOf("</head>"));
const body = html.slice(html.indexOf("<body>") + 6, html.indexOf("</body>"));

// 3. keep only what belongs at the top of an artifact file
const keep = head
  .split("\n")
  .filter((line) => /<title>|fonts\.googleapis|fonts\.gstatic|rel="stylesheet"|rel="preconnect"|name="theme-color"|rel="icon"/.test(line))
  .join("\n")
  // the artifact gallery wants a name, not a name plus an explainer
  .replace(/<title>[^<]*<\/title>/, "<title>IntelPulse</title>");

const banner = `<!-- IntelPulse — shareable demo build.
     Generated by scripts/build-artifact.mjs from web/. Demo mode only: every
     indicator is scored in the browser against a bundled SYNTHETIC dataset
     (RFC 5737 documentation addresses, RFC 2606 reserved domains). No vendor
     API is called and nothing here describes a real host. -->`;

writeFileSync(join(out, "index.html"), [banner, keep.trim(), body.trim()].join("\n\n"));

for (const file of readdirSync(join(root, "web", "assets"))) {
  copyFileSync(join(root, "web", "assets", file), join(out, "assets", file));
}

// The landing page links on to the analyst workbench and the campaign graph.
// Ship them beside it so those links resolve in the published build too.
for (const page of ["workbench.html", "explorer.html"]) {
  copyFileSync(join(root, "web", page), join(out, page));
}

const size = readFileSync(join(out, "index.html")).length;
console.log("built dist/artifact/index.html (" + size + " bytes) + " +
  readdirSync(join(out, "assets")).length + " assets + workbench.html + explorer.html");
